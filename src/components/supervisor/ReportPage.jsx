    doc.rect(0, 30, pageWidth, 10, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFontSize(12);
    doc.setFont('helvetica', 'bold');
    doc.text('CONFIDENTIAL REPORT', pageWidth / 2, 36, { align: 'center' });

